const DICT: Record<string, Record<string, string>> = { zh, en };

export const available: { code: string; label: string }[] = [
  { code: "zh", label: "简体中文" },
  { code: "en", label: "English" },
];

const listeners = new Set<() => void>();

let locale: Locale = "zh";

/** 归一化语言代码：仅 "en" 保留为英文，其余一律中文 */
function normalize(code: string): Locale {
  return code === "en" ? "en" : "zh";
}

/** 安全查表：缺失键返回 undefined，便于回退 */
function lookup(table: Record<string, string>, key: string): string | undefined {
  return Object.prototype.hasOwnProperty.call(table, key) ? table[key] : undefined;
}

function notify(): void {
  listeners.forEach((fn) => fn());
}

/** 同步 <html lang> 与 document.title；无 DOM 环境（测试 / SSR）直接跳过 */
function syncDocument(): void {
  if (typeof document === "undefined" || !document.documentElement) return;
  document.documentElement.setAttribute("lang", locale === "zh" ? "zh-CN" : "en");
  document.title = t("app.title");
}

/** 当前语言代码，"zh" | "en" */
export function getLocale(): string {
  return locale;
}

/** 按系统语言推断默认语言：以 zh 开头取中文，其余取英文 */
export function detect(): string {
  if (typeof navigator === "undefined") return "en";
  const nav = String(
    (navigator.language || (navigator.languages && navigator.languages[0]) || "").toLowerCase()
  );
  return nav.indexOf("zh") === 0 ? "zh" : "en";
}

/** 切换语言；默认 emit，即通知所有订阅者；opts.emit === false 时不通知 */
export function setLocale(code: string, opts?: { emit?: boolean }): void {
  const next = normalize(code);
  const changed = next !== locale;
  locale = next;
  syncDocument();
  if (changed && (!opts || opts.emit !== false)) notify();
}

/**
 * 取词 + {name} 占位符插值。
 * 回退顺序：当前语言 → 调用方传入的 fallback 原文 → 中文 zh → key 本身。
 */
export function t(key: string, vars?: Record<string, unknown>, fallback?: string): string {
  const table = DICT[locale] || zh;
  let s = lookup(table, key);
  if (s == null) s = fallback;
  if (s == null) s = lookup(zh, key);
  if (s == null) s = key;
  if (vars) {
    s = s.replace(/\{(\w+)\}/g, (m: string, name: string) => {
      const v = vars[name];
      return v != null ? String(v) : m;
    });
  }
  return s;
}

/** 订阅语言变化，返回取消函数 */
export function subscribe(fn: () => void): () => void {
  listeners.add(fn);
  return () => {
    listeners.delete(fn);
  };
}

/** React hook：随语言变化重渲染，返回取词函数 */
export function useT(): (key: string, vars?: Record<string, unknown>, fallback?: string) => string {
  useSyncExternalStore(subscribe, getLocale, getLocale);
  return t;
}

/** React hook：随语言变化重渲染，返回当前语言 */
export function useLocale(): string {
  return useSyncExternalStore(subscribe, getLocale, getLocale);
}

